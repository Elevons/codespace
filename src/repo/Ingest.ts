import { Architecture, type IArchitecture } from './Architecture.ts'
import type { Graph } from './Graph.ts'
import type { Repo } from './Repo.ts'

/** The most items one batch holds unless asked for more. */
export const DefaultBatch = 12

/** The largest file read for a batch, in characters. */
const MaxFileChars = 20_000

/** Files whose text is generated, with the summary each gets instead of being read. */
const Skipped = new Map<string, string>([
    ['package-lock.json', 'The locked dependency tree, generated by npm.'],
    ['npm-shrinkwrap.json', 'The locked dependency tree, generated by npm.'],
    ['yarn.lock', 'The locked dependency tree, generated by Yarn.'],
    ['pnpm-lock.yaml', 'The locked dependency tree, generated by pnpm.'],
    ['bun.lockb', 'The locked dependency tree, generated by Bun.'],
    ['Cargo.lock', 'The locked dependency tree, generated by Cargo.'],
    ['go.sum', 'The checksums of the Go modules this repository depends on, generated by the Go toolchain.'],
    ['poetry.lock', 'The locked dependency tree, generated by Poetry.'],
    ['Pipfile.lock', 'The locked dependency tree, generated by pipenv.'],
    ['composer.lock', 'The locked dependency tree, generated by Composer.'],
    ['Gemfile.lock', 'The locked dependency tree, generated by Bundler.'],
])

/** The folders whose files are someone else's code or built output, not written by hand. */
const SkippedFolders = ['vendor', 'third_party', 'dist', 'build', 'out', '.codespace']

/** One file in a batch: what it is, and enough of it to write its summary. */
export interface IIngestFile
{
    /** Its repository-relative path. */
    path: string
    /** What its entry still lacks: "summary", "system", "layer", or "tags". */
    missing: string[]
    /** Its text, cut to a readable length. */
    source: string
    /** Whether the source was cut. */
    truncated: boolean
    /** What it imports, among the repository's files. */
    imports: string[]
    /** What imports it. */
    usedBy: string[]
}

/** One folder in a batch: its files and folders, each with the summary it has so far. */
export interface IIngestFolder
{
    /** Its repository-relative path. */
    path: string
    /** The file and folder names directly inside it, each with its current summary. */
    children: Array<{ path: string, summary: string }>
}

/** How much of the codebase still has to be described. */
export interface IIngestStatus
{
    /** Files that still need a summary. */
    files: number
    /** Files whose entry is missing a system, a layer, or tags. */
    incomplete: number
    /** Folders that still need a summary. */
    folders: number
    /** All of them together. */
    remaining: number
}

/** What `next` answers. */
export interface IIngestBatch
{
    /** Files that still need a summary, for the agent to read. */
    files: IIngestFile[]
    /** Folders whose contents are all summarized, once no files are left. */
    folders: IIngestFolder[]
    /** Generated files that were summarized here, so the agent need not read them. */
    skipped: Array<{ path: string, summary: string }>
    /** The layer names declared in the architecture file; empty means none are declared yet. Layers are shared by every system. */
    layers: string[]
    /** The system names declared in the architecture file; empty means none are declared yet. */
    systems: string[]
    /** Files and folders still to describe, including those this batch hands out. */
    remaining: number
}

/**
 * The fixed summary a generated or vendored file gets, or null for a file worth reading.
 * @param path the file's repository-relative path
 */
export function SkippedSummary(path: string): string | null
{
    const name = path.slice(path.lastIndexOf('/') + 1)
    const fixed = Skipped.get(name)
    if (fixed !== undefined) return fixed
    if (/\.min\.(js|css)$/.test(name) || name.endsWith('.map')) return 'Built or minified output, generated from source.'
    const segments = path.split('/').slice(0, -1)
    const vendored = segments.find((segment) => SkippedFolders.includes(segment))
    if (vendored === '.codespace') return 'Codespace metadata, written by the map and its tools rather than by hand.'
    if (vendored !== undefined) return `Built or third-party code under "${vendored}", not written in this repository.`
    return null
}

/** What is left to describe, and which files are generated, worked out from the file list alone. */
interface IPlan
{
    known: string[]
    pending: string[]
    incomplete: string[]
    skipped: Array<{ path: string, summary: string }>
    folders: string[]
}

/**
 * What one file's entry still lacks: "summary", "system", "layer", or "tags". A system the
 * architecture does not declare counts as missing, since the map refuses to place the file.
 * @param architecture what the architecture file says
 * @param path the file's repository-relative path
 */
function Lacks(architecture: IArchitecture, path: string): string[]
{
    const entry = architecture.files[path]
    const lacks: string[] = []
    if (entry?.summary === undefined) lacks.push('summary')
    if (entry?.system === undefined || !(entry.system in architecture.systems)) lacks.push('system')
    if (entry?.layer === undefined) lacks.push('layer')
    if ((entry?.tags?.length ?? 0) === 0) lacks.push('tags')
    return lacks
}

/**
 * Works out what still needs a summary: files without one, and folders without one.
 * @param repo the repository being mapped
 * @param architecture what the architecture file says
 */
async function PlanAsync(repo: Repo, architecture: IArchitecture): Promise<IPlan>
{
    const known = await repo.ListFilesAsync()
    const summaries = new Set(Object.entries(architecture.files).filter(([, entry]) => entry.summary !== undefined).map(([path]) => path))

    // Generated and vendored files are settled here, so the agent never spends a read on them.
    const skipped: Array<{ path: string, summary: string }> = []
    const pending: string[] = []
    const incomplete: string[] = []
    for (const path of known)
    {
        const fixed = SkippedSummary(path)
        if (fixed !== null) { if (!summaries.has(path)) skipped.push({ path, summary: fixed }); continue }
        if (!summaries.has(path)) { pending.push(path); continue }

        // A file that is summarized but has no system, layer, or tags comes back for a second pass.
        if (Lacks(architecture, path).some((field) => field !== 'summary')) incomplete.push(path)
    }

    const folders = [...Architecture.Folders(known)].filter((path) => architecture.folders[path] === undefined)
    return { known, pending, incomplete, skipped, folders }
}

/**
 * Counts what still has no summary, for the page's ingest status.
 * @param repo the repository being mapped
 * @param architecture what the architecture file says
 */
export async function StatusAsync(repo: Repo, architecture: IArchitecture): Promise<IIngestStatus>
{
    const plan = await PlanAsync(repo, architecture)
    return {
        files: plan.pending.length, incomplete: plan.incomplete.length, folders: plan.folders.length,
        remaining: plan.pending.length + plan.incomplete.length + plan.folders.length,
    }
}

/**
 * Chooses what the agent reads next: files without a summary, then folders whose files are all done.
 * @param repo the repository being mapped
 * @param architecture what the architecture file says
 * @param graph the imports between code files
 * @param size the most files or folders to hand out
 */
export async function NextBatchAsync(repo: Repo, architecture: IArchitecture, graph: Graph, size: number): Promise<IIngestBatch>
{
    const { known, pending, incomplete, skipped, folders } = await PlanAsync(repo, architecture)
    const summaries = new Map<string, string>()
    for (const [path, entry] of Object.entries(architecture.files)) if (entry.summary !== undefined) summaries.set(path, entry.summary)
    const remaining = pending.length + incomplete.length + folders.length
    const layers = architecture.layers
    const systems = Object.keys(architecture.systems)

    /** What one file's entry still lacks. */
    const missing = (path: string): string[] => Lacks(architecture, path)

    // Files come first: undescribed ones, then those whose entry is missing a system, layer, or tags. A folder
    // is only ready once every file under it has been described.
    const pool = [...pending, ...incomplete]
    if (pool.length > 0)
    {
        const usedBy = new Map<string, string[]>()
        for (const [from, to] of graph.Edges())
        {
            const users = usedBy.get(to) ?? []
            users.push(from)
            usedBy.set(to, users)
        }
        const files: IIngestFile[] = []
        for (const path of pool.slice(0, size))
        {
            const full = await repo.ReadFileAsync(path).catch(() => '')
            files.push({ path, missing: missing(path), source: full.slice(0, MaxFileChars), truncated: full.length > MaxFileChars, imports: graph.ImportsOf(path), usedBy: usedBy.get(path) ?? [] })
        }
        return { files, folders: [], skipped, layers, systems, remaining }
    }

    // Then folders, deepest first, with what is inside them already summarized.
    const done = (path: string): boolean => summaries.has(path) || architecture.folders[path] !== undefined
    const ready = folders
        .filter((folder) => known.every((path) => !path.startsWith(folder + '/') || done(path)))
        .filter((folder) => [...Architecture.Folders(known)].every((inner) => inner.slice(0, inner.lastIndexOf('/')) !== folder || done(inner)))
        .sort((a, b) => b.split('/').length - a.split('/').length || (a < b ? -1 : 1))
        .slice(0, size)
    const batch: IIngestFolder[] = ready.map((path) =>
    {
        const children = known
            .filter((file) => file.slice(0, file.lastIndexOf('/')) === path)
            .map((file) => ({ path: file, summary: summaries.get(file) ?? architecture.folders[file] ?? '' }))
        const childFolders = [...Architecture.Folders(known)]
            .filter((folder) => folder.slice(0, folder.lastIndexOf('/')) === path)
            .map((folder) => ({ path: folder, summary: architecture.folders[folder] ?? '' }))
        return { path, children: [...childFolders, ...children].sort((a, b) => (a.path < b.path ? -1 : 1)) }
    })
    return { files: [], folders: batch, skipped, layers, systems, remaining }
}
